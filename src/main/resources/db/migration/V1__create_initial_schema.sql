CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(254) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    role VARCHAR(20) NOT NULL,
    enabled BOOLEAN NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE vehicles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    name VARCHAR(100) NOT NULL,
    plate VARCHAR(30),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE odometer_readings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id BIGINT NOT NULL REFERENCES vehicles(id),
    reading_km NUMERIC(12, 2) NOT NULL,
    taken_at TIMESTAMP WITH TIME ZONE NOT NULL,
    photo_path VARCHAR(500),
    source VARCHAR(10) NOT NULL,
    ai_confidence VARCHAR(10),
    note VARCHAR(500)
);

CREATE TABLE fuel_fill_ups (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id BIGINT NOT NULL REFERENCES vehicles(id),
    filled_at TIMESTAMP WITH TIME ZONE NOT NULL,
    litres NUMERIC(8, 3) NOT NULL,
    total_cost NUMERIC(12, 2) NOT NULL,
    odometer_km NUMERIC(12, 2) NOT NULL,
    full_tank BOOLEAN NOT NULL
);

CREATE INDEX idx_vehicles_user_id ON vehicles(user_id);
CREATE INDEX idx_odometer_readings_vehicle_taken_at ON odometer_readings(vehicle_id, taken_at);
CREATE INDEX idx_fuel_fill_ups_vehicle_filled_at ON fuel_fill_ups(vehicle_id, filled_at);
